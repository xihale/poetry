# 残句：标题就是「句」的那些（存下来的一联，不是完整作品），「句 其四」也在内。
# 名句命中的除外 —— 苏麟「近水楼台先得月」本身就是断句。
FRAGMENT = re.compile(r"^句(\s|其|$)")
# 少于这么多字的不进席位：一联、一句。名句命中的除外。
MIN_CHARS = 16

# 伪作者：郊庙朝会歌辞（1,639 首祭祀乐歌）不算作者。它们只能靠名句进来。
PSEUDO_AUTHOR = {"郊庙朝会歌辞"}


def _weight(rec: dict) -> int:
    return len(re.sub(r"\s", "", rec["text"]))


def select(records: list[dict]) -> list[dict]:
    """全宋诗 / 现代诗 换成选本，其余诗集原样返回。

    一位诗人取几首由白名单里的席位决定，席位内的次序见模块开头：
    名句名篇先，短制先，源序最后。
    """
    sources = {c[0] for c in COLLECTIONS}
    keep: set[int] = set()
    for source, name, seats, lines, poems in COLLECTIONS:
        recs = [r for r in records if r["coll"] == source]
        by_author: dict[str, list[dict]] = defaultdict(list)
        for r in recs:
            by_author[r["author"]].append(r)

        taken: list[dict] = []
        for author, rs in by_author.items():
            famous, ordinary = [], []
            for r in rs:
                title = r["title"].strip()
                body = re.sub(r"\s", "", r["text"])
                # 名句命中的，或题目本身就是名篇的：不受席位与长度限制
                if any(line in body for line in lines) or (author, title) in poems:
                    famous.append(r)
                elif (author in seats and author not in PSEUDO_AUTHOR
                      and not FRAGMENT.match(title) and _weight(r) >= MIN_CHARS):
                    ordinary.append(r)
            ordinary.sort(key=_weight)  # 短制先；同长保持源序（排序是稳定的）
            taken.extend(famous)
            taken.extend(ordinary[: max(0, seats.get(author, 0) - len(famous))])

        for r in taken:
            r["coll"] = name
            keep.add(id(r))
        print(f"  {source:>6} -> {name}: {len(recs):>7} -> {len(taken):>5} 首"
              f"  {len({r['author'] for r in taken}):>4} 位作者")
    # 原顺序不变，只是把没选中的剔除
    return [r for r in records if r["coll"] not in sources or id(r) in keep]
